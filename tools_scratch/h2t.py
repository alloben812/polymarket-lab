import sys, re, html
s = open(sys.argv[1], encoding='utf-8', errors='replace').read()
s = re.sub(r'(?is)<(script|style|svg|noscript)[^>]*>.*?</\1>', ' ', s)
m = re.search(r'(?is)<article.*?</article>', s)
if m and len(sys.argv) > 2 and sys.argv[2] == 'article': s = m.group(0)
s = re.sub(r'(?i)<(br|/p|/h\d|/li|/tr|/div)[^>]*>', '\n', s)
s = re.sub(r'(?i)<a [^>]*href="([^"]+)"[^>]*>', r' [\1] ', s)
s = re.sub(r'<[^>]+>', ' ', s)
s = html.unescape(s)
s = re.sub(r'[ \t]+', ' ', s)
s = re.sub(r'\n\s*\n+', '\n', s)
print(s.strip())
