"""Reconstruct per-market behaviour of the wallet: pair cost, residual, fee, PnL, timing."""
import json,sys,collections,re,math,statistics as st
rows=[json.loads(l) for l in open(sys.argv[1])]
res=json.load(open(sys.argv[2]))
FEE=float(sys.argv[3]) if len(sys.argv)>3 else 0.05
mk=collections.defaultdict(list)
for r in rows: mk[r['condition_id']].append(r)
M=[]
for c,rs in mk.items():
    rv=res.get(c)
    if not rv or not rv['resolved']: continue
    m=re.search(r'-(\d{9,})$',rs[0]['slug']); t0=int(m.group(1))
    win='Up' if rv['final'].get('Up')==1.0 else ('Down' if rv['final'].get('Down')==1.0 else None)
    if win is None: continue
    d=dict(c=c,t0=t0,win=win)
    for o in ('Up','Down'):
        for role in ('T','M'):
            sel=[r for r in rs if r['outcome']==o and r['role']==role and r['side']=='BUY']
            d[f'sh_{o}_{role}']=sum(r['size'] for r in sel); d[f'usd_{o}_{role}']=sum(r['size']*r['price'] for r in sel)
        d[f'sh_{o}']=d[f'sh_{o}_T']+d[f'sh_{o}_M']; d[f'usd_{o}']=d[f'usd_{o}_T']+d[f'usd_{o}_M']
    d['sells']=sum(1 for r in rs if r['side']!='BUY')
    d['fee']=sum(FEE*r['size']*r['price']*(1-r['price']) for r in rs if r['role']=='T')
    d['fee_gen_maker']=sum(FEE*r['size']*r['price']*(1-r['price']) for r in rs if r['role']=='M')
    d['cost']=d['usd_Up']+d['usd_Down']
    d['payoff']=d['sh_'+win]
    d['gross']=d['payoff']-d['cost']; d['net']=d['gross']-d['fee']
    d['pairs']=min(d['sh_Up'],d['sh_Down']); d['resid']=d['sh_Up']-d['sh_Down']
    d['vw_Up']=d['usd_Up']/d['sh_Up'] if d['sh_Up'] else None; d['vw_Down']=d['usd_Down']/d['sh_Down'] if d['sh_Down'] else None
    d['rows']=rs
    M.append(d)
M.sort(key=lambda d:d['t0'])
n=len(M); print("markets",n,"sell rows",sum(d['sells'] for d in M))
both=[d for d in M if d['sh_Up']>0 and d['sh_Down']>0]
print(f"markets with both sides: {len(both)} ({len(both)/n*100:.1f}%)")
tot=lambda k: sum(d[k] for d in M)
cost=tot('cost'); print(f"cost {cost:.0f}  payoff {tot('payoff'):.0f}  GROSS {tot('gross'):.0f}  est.taker fees {tot('fee'):.0f}  NET(before rebates) {tot('net'):.0f}")
print(f"gross/cost {tot('gross')/cost*100:.2f}%  fee/cost {tot('fee')/cost*100:.2f}%  net/cost {tot('net')/cost*100:.2f}%")
print(f"est. taker fees generated by its MAKER fills (paid by counterparties): {tot('fee_gen_maker'):.0f}")
# pair economics
pairs=tot('pairs'); 
pc=[(d['vw_Up']+d['vw_Down'], d['pairs']) for d in both]
wavg=sum(a*b for a,b in pc)/sum(b for a,b in pc)
print(f"\nPAIRS: total complete sets {pairs:.0f}; size-weighted pair cost {wavg:.4f} -> gap to $1 = {(1-wavg)*100:.2f}c per pair; median pair cost {st.median(a for a,b in pc):.4f}")
print(f"  share of markets with pair cost < 1: {sum(1 for a,b in pc if a<1)/len(pc)*100:.1f}%")
# per-share pair cost incl. fee
feeps=tot('fee')/ (tot('sh_Up')+tot('sh_Down'))
print(f"  avg taker fee per share bought (all shares): {feeps*100:.3f}c -> per pair {(2*feeps)*100:.2f}c")
# residual economics: decompose PnL = pairs*(1-paircost) + residual leg
pnl_pairs=0; pnl_res=0; res_sh=0; res_right=0; res_cost=0
for d in M:
    if d['sh_Up']>0 and d['sh_Down']>0:
        pnl_pairs+=d['pairs']*(1-(d['vw_Up']+d['vw_Down']))
    side='Up' if d['resid']>0 else 'Down'
    r=abs(d['resid'])
    if r>0:
        vw=d['vw_'+side]; res_sh+=r; res_cost+=r*vw
        pay=r if d['win']==side else 0
        pnl_res+=pay-r*vw
        if d['win']==side: res_right+=1
nres=sum(1 for d in M if abs(d['resid'])>0)
print(f"\nDECOMPOSITION (gross, before fees): pairs leg {pnl_pairs:.0f}  + residual leg {pnl_res:.0f}  = {pnl_pairs+pnl_res:.0f}")
print(f"  residual: {res_sh:.0f} shares, avg cost {res_cost/res_sh:.3f}, direction correct in {res_right}/{nres} markets = {res_right/nres*100:.1f}%")
# residual hit-rate weighted by shares & relative size
wr=sum(abs(d['resid']) for d in M if d['win']==('Up' if d['resid']>0 else 'Down'))/res_sh
print(f"  share-weighted residual win rate {wr*100:.1f}% vs avg residual cost {res_cost/res_sh*100:.1f}c  => edge {(wr-res_cost/res_sh)*100:.1f}c/share")
print(f"  residual size as % of total shares: {res_sh/(tot('sh_Up')+tot('sh_Down'))*100:.1f}%;  avg |resid| per market {res_sh/n:.0f} sh; avg pairs per market {pairs/n:.0f}")
# by role: EV of maker buys vs taker buys
for role in ('M','T'):
    sh=usd=pay=fee=0
    for d in M:
        for o in ('Up','Down'):
            s=d[f'sh_{o}_{role}']; sh+=s; usd+=d[f'usd_{o}_{role}']; pay+= s if d['win']==o else 0
        if role=='T': fee+=d['fee']
    print(f"\nROLE {role}: shares {sh:.0f} avg px {usd/sh:.4f} realized win-rate/share {pay/sh:.4f} => gross edge {(pay-usd)/sh*100:+.2f}c/share ({(pay-usd):+.0f}$), fees {fee:.0f}$, net {(pay-usd-fee):+.0f}$")
# per-market pnl distribution
nets=[d['net'] for d in M]; costs=[d['cost'] for d in M]
print(f"\nper-market: avg cost {st.mean(costs):.0f}$ median {st.median(costs):.0f}$ max {max(costs):.0f}$; net mean {st.mean(nets):+.2f}$ sd {st.pstdev(nets):.1f}$ win% {sum(1 for x in nets if x>0)/n*100:.1f}  worst {min(nets):.0f}$ best {max(nets):.0f}$")
se=st.pstdev(nets)/math.sqrt(n)
print(f"  t-stat of mean net per market: {st.mean(nets)/se:.2f}  (sum {sum(nets):.0f} ± {1.96*se*n:.0f} 95%)")
json.dump([{k:v for k,v in d.items() if k!='rows'} for d in M], open(sys.argv[1].replace('.jsonl','_markets.json'),'w'))
