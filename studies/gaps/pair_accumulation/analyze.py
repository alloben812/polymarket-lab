SER = [name(s) for s in SERIES]
DAYS = {"early": 4.0, "late": 2.0, "all": 6.0}


def cl_mean(x, g):
    """Mean of x with SE clustered by g (CR1 small-sample factor)."""
    x = np.asarray(x, float)
    n = len(x)
    if n < 2:
        return (float(x.mean()) if n else float("nan")), float("nan")
    m = x.mean()
    s = pd.Series(x - m).groupby(np.asarray(g)).sum().values
    G = len(s)
    if G < 2:
        return m, float("nan")
    se = math.sqrt((s ** 2).sum() * G / (G - 1)) / n
    return float(m), float(se)


def windows_table(legs, scen):
    """One row per (series, L, t0): number of filled legs, net USD, capital USD, single-leg info."""
    d = legs.copy()
    d["S"] = NOTIONAL / d["L"]
    d["filled"] = d["placeable"] & d[f"t_{scen}"].notna()
    d["pnl"] = np.where(d["filled"], d["S"] * (d["won"].astype(float) - d["L"]), 0.0)
    d["tf"] = np.where(d["filled"], d[f"t_{scen}"], np.nan)
    g = d.groupby(["series", "L", "t0"], sort=False)
    w = g.agg(late=("late", "first"), nf=("filled", "sum"), net=("pnl", "sum"),
              nplace=("placeable", "sum"), t_first=("tf", "min"), t_second=("tf", "max")).reset_index()
    single = d[d.filled].groupby(["series", "L", "t0"]).agg(won1=("won", "first"))
    w = w.merge(single, on=["series", "L", "t0"], how="left")
    w.loc[w.nf != 1, "won1"] = np.nan
    w.loc[w.nf != 2, "t_second"] = np.nan
    w["cap"] = w.nf * NOTIONAL
    w["hour"] = w.t0 // 3600
    w["day"] = w.t0 // 86400
    return w, d


def cell_stats(w, d, L, days):
    n = len(w)
    out = {"markets": n}
    if n == 0:
        return out
    out["skip_legs"] = int(2 * n - w.nplace.sum())
    for k in (0, 1, 2):
        out[f"p{k}"] = float((w.nf == k).mean())
    m, se = cl_mean(w.net, w.hour)
    out.update(net=m, se=se, t=(m / se if se and se > 0 else float("nan")), lo=m - 1.96 * se, hi=m + 1.96 * se)
    nf = int(w.nf.sum())
    out["filled_legs"] = nf
    out["net_per_leg"] = float(w.net.sum() / nf) if nf else float("nan")
    out["ret_cap"] = float(w.net.sum() / w.cap.sum()) if w.cap.sum() else float("nan")
    s1 = w[w.nf == 1]
    out["single_n"] = len(s1)
    out["single_won"] = int(s1.won1.sum()) if len(s1) else 0
    lo, hi = wilson(out["single_won"], len(s1)) if len(s1) else (float("nan"), float("nan"))
    out["single_wr"] = out["single_won"] / len(s1) if len(s1) else float("nan")
    out["single_wr_lo"], out["single_wr_hi"] = lo, hi
    out["single_net_sum"] = float(s1.net.sum())
    out["pair_n"] = int((w.nf == 2).sum())
    out["pair_net_sum"] = float(w[w.nf == 2].net.sum())
    out["fill_windows"] = int((w.nf > 0).sum())
    out["legs_per_day"] = nf / days
    out["t_first_med"] = float(w.t_first.median()) if w.t_first.notna().any() else float("nan")
    out["t_second_med"] = float(w.t_second.median()) if w.t_second.notna().any() else float("nan")
    out["net_sum"] = float(w.net.sum())
    return out


def main():
    legs = pd.read_parquet(BIG / "legs_main.parquet")
    mk = pd.read_parquet(BIG / "markets_main.parquet")
    lines = ["# Tables (generated by analyze.py)", ""]
    # ---- sanity
    ok = mk[mk.status == "ok"].copy()
    lines += ["## Sanity", "", "| series | markets ok | missing/no tape | with print in window | tape shares / volume (median) | "
              "prints 0.45-0.55 shares | won share | skipped legs (placement) |", "|---|---|---|---|---|---|---|---|"]
    for s in SER:
        a = mk[mk.series == s] if "series" in mk else mk.iloc[0:0]
        o = ok[ok.series == s]
        bad = int(((mk.asset + "-" + mk.dur) == s).sum() - len(o))
        ratio = (o.tape_shares / o.volume.astype(float)).replace([np.inf, -np.inf], np.nan).median()
        sk = legs[(legs.series == s) & (~legs.placeable)]
        lines.append(f"| {s} | {len(o)} | {bad} | {(o.n_inwin > 0).mean():.1%} | {ratio:.4f} | {o.mid_sh.sum():,.0f} | "
                     f"{o.mid_win_sh.sum() / max(o.mid_sh.sum(), 1):.3f} | {len(sk)} of {len(legs[legs.series == s])} |")
    lines.append("")
    rows = []
    for scen in ("cons", "opt"):
        W, D = windows_table(legs, scen)
        for L in LEVELS:
            for s in SER + ["POOLED"]:
                for per in ("early", "late", "all"):
                    w = W[W.L == L]
                    if s != "POOLED":
                        w = w[w.series == s]
                    if per != "all":
                        w = w[w.late == (per == "late")]
                    st = cell_stats(w, None, L, DAYS[per])
                    rows.append({"scen": scen, "L": L, "series": s, "period": per, **st})
        if scen == "cons":
            Wc = W
    C = pd.DataFrame(rows)
    C.to_csv(OUT / "cells.csv", index=False, float_format="%.5g")
    # ---- main tables
    for scen in ("cons", "opt"):
        lines += [f"## Cells, scenario {scen}", "",
                  "| L | series | period | markets | P(0/1/2 legs) | net $/window (95% CI) | t | net $ per filled leg | "
                  "single legs won / n (rate) | pairs | legs/day | med s to 1st / 2nd fill |",
                  "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for L in LEVELS:
            for s in SER + ["POOLED"]:
                for per in ("early", "late", "all"):
                    r = C[(C.scen == scen) & (C.L == L) & (C.series == s) & (C.period == per)].iloc[0]
                    if r.markets == 0:
                        continue
                    lines.append(
                        f"| {L:.2f} | {s} | {per} | {r.markets:.0f} | {r.p0:.2f}/{r.p1:.2f}/{r.p2:.2f} | {r.net:+.3f} "
                        f"({r.lo:+.3f}, {r.hi:+.3f}) | {r.t:+.2f} | {r.net_per_leg:+.3f} | {r.single_won:.0f}/{r.single_n:.0f} "
                        f"({r.single_wr:.3f}) | {r.pair_n:.0f} | {r.legs_per_day:.1f} | {r.t_first_med:.0f} / {r.t_second_med:.0f} |")
        lines.append("")
    # ---- decision rule (protocol 9)
    hist = None
    try:
        hl = pd.read_parquet(BIG / "legs_hist.parquet")
        Wh, _ = windows_table(hl, "cons")
        hist = {L: cl_mean(Wh[Wh.L == L].net, Wh[Wh.L == L].hour) for L in LEVELS}
        Who, _ = windows_table(hl, "opt")
        hist_opt = {L: cl_mean(Who[Who.L == L].net, Who[Who.L == L].hour) for L in LEVELS}
        lines += ["## Secondary history: BTC 5m, every 4th window, 2026-09-01 .. 11-20", "",
                  "| L | scenario | markets | P(0/1/2) | net $/window (95% CI) | t | single won/n | by month net $/window |",
                  "|---|---|---|---|---|---|---|---|"]
        for scen, WW in (("cons", Wh), ("opt", Who)):
            for L in LEVELS:
                w = WW[WW.L == L]
                st = cell_stats(w, None, L, 81)
                mon = w.groupby(pd.to_datetime(w.t0, unit="s").dt.month).net.mean()
                lines.append(f"| {L:.2f} | {scen} | {st['markets']} | {st['p0']:.2f}/{st['p1']:.2f}/{st['p2']:.2f} | "
                             f"{st['net']:+.3f} ({st['lo']:+.3f}, {st['hi']:+.3f}) | {st['t']:+.2f} | "
                             f"{st['single_won']}/{st['single_n']} | " + ", ".join(f"{k}: {v:+.3f}" for k, v in mon.items()) + " |")
        lines.append("")
    except FileNotFoundError:
        lines += ["(history legs not built)", ""]
    lines += ["## Decision rule (protocol 9)", "", "| scen | L | series | early net | late net | late t | all t | late fill windows | verdict |",
              "|---|---|---|---|---|---|---|---|---|"]
    for scen in ("cons", "opt"):
        for L in LEVELS:
            for s in SER:
                g = lambda per: C[(C.scen == scen) & (C.L == L) & (C.series == s) & (C.period == per)].iloc[0]  # noqa: E731
                e, l, a = g("early"), g("late"), g("all")
                ok_ = (e.net > 0) and (l.net > 0) and (l.t >= 2.0) and (a.t >= 3.3) and (l.fill_windows >= 20)
                if ok_ and s == "btc-5m" and hist is not None:
                    hm, hse = (hist if scen == "cons" else hist_opt)[L]
                    ok_ = not (hm < 0 and hm / hse <= -2)
                lines.append(f"| {scen} | {L:.2f} | {s} | {e.net:+.3f} | {l.net:+.3f} | {l.t:+.2f} | {a.t:+.2f} | "
                             f"{l.fill_windows:.0f} | {'PASS' if ok_ else '-'} |")
    lines.append("")
    (OUT / "tables.md").write_text("\n".join(lines))
    print("\n".join(lines[-110:]))


if __name__ == "__main__":
    main()
